// Generates src/lib/api/schema.d.ts (TypeScript types of the whole Django API) from the
// OpenAPI schema that drf-spectacular builds, offline: no server, no login needed.
//
//   npm run api:types   regenerate the file after a backend change, then commit it
//   npm run api:check   fail if the file no longer matches the backend (run by check_all.ps1)
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const checkOnly = process.argv.includes("--check");
const frontend = path.resolve(import.meta.dirname, "..");
const backend = path.resolve(frontend, "..", "backend");
const target = path.join(frontend, "src", "lib", "api", "schema.d.ts");

const python = [
  path.join(backend, ".venv", "Scripts", "python.exe"), // Windows
  path.join(backend, ".venv", "bin", "python"), // macOS, Linux
].find((candidate) => existsSync(candidate));
if (!python) {
  console.error(`Python virtual environment not found in ${backend}\\.venv (see backend/README.md).`);
  process.exit(1);
}

const workDir = mkdtempSync(path.join(tmpdir(), "enp-api-schema-"));
const schemaFile = path.join(workDir, "openapi.json");
let generated;
try {
  // --lang en: descriptions in English whatever the default language, so the output is stable.
  execFileSync(
    python,
    ["manage.py", "spectacular", "--format", "openapi-json", "--lang", "en", "--fail-on-warn", "--file", schemaFile],
    { cwd: backend, stdio: "inherit", env: { ...process.env, PYTHONUTF8: "1" } },
  );
  const schema = JSON.parse(readFileSync(schemaFile, "utf8"));
  const header =
    "// Generated by scripts/generate-api-types.mjs from the Django API schema. Do not edit:\n" +
    "// run `npm run api:types` after a backend change.\n\n";
  generated = header + astToString(await openapiTS(schema));
} finally {
  rmSync(workDir, { recursive: true, force: true });
}

const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
if (checkOnly) {
  if (current !== generated) {
    console.error("src/lib/api/schema.d.ts does not match the backend API: run `npm run api:types`.");
    process.exit(1);
  }
  console.log("API types match the backend.");
} else {
  writeFileSync(target, generated);
  console.log(`Written ${path.relative(frontend, target)}`);
}
